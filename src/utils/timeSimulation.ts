export interface TimeBasedMetrics {
  // Time-based simulation for volunteer program metrics
  month: string;
  totalVolunteers: number;
  totalHours: number;
  studentsReached: number;
  returnRate: number;
  roi: number;
}

export function generateTimeSimulationData(initialData: {
  totalVolunteers: number;
  totalHours: number;
  studentsReached: number;
  retentionRate: number;
  companyInvestment: number;
}): TimeBasedMetrics[] {
  const simulationData: TimeBasedMetrics[] = [];
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  
  // Start with initial data
  let currentVolunteers = initialData.totalVolunteers;
  let currentHours = initialData.totalHours;
  let currentStudentsReached = initialData.studentsReached;
  
  months.forEach((month, index) => {
    // Base monthly data with some variance for realism
    const baseOpportunitiesPerMonth = 5; // 3-8 opportunities per month (average 5)
    const variance = Math.floor(Math.random() * 3) - 1; // -1, 0, or 1 for variance
    const opportunitiesPerMonth = Math.max(3, Math.min(8, baseOpportunitiesPerMonth + variance));
    
    // 1-20 employees per opportunity with up to 10 students per employee
    const minParticipantsPerOpportunity = 1;
    const maxParticipantsPerOpportunity = 20;
    const participantsPerOpportunity = Math.floor(Math.random() * (maxParticipantsPerOpportunity - minParticipantsPerOpportunity + 1)) + minParticipantsPerOpportunity;
    
    // Calculate new opportunities and participants
    const newOpportunities = opportunitiesPerMonth;
    const newParticipants = newOpportunities * participantsPerOpportunity;
    
    // Calculate students reached (10 students per employee maximum)
    const maxStudentsPerEmployee = 10;
    const newStudentsReached = currentStudentsReached + Math.min(newParticipants * maxStudentsPerEmployee, newParticipants * maxStudentsPerEmployee);
    
    // Calculate new hours based on students reached (each student requires ~1 employee hour)
    const newHours = currentHours + newParticipants;
    
    // Calculate new volunteers (could be same as participants)
    const newVolunteers = currentVolunteers + newParticipants;
    
    // Calculate return rate (percentage of volunteers who participate in more than one activity)
    // This simulates the platform's success in encouraging repeat participation
    let returnRate = initialData.retentionRate;
    if (index > 0) {
      // Gradually improve return rate over time (from current to 100%)
      const improvement = 0.5 + Math.random() * 0.3; // 0.5% to 0.8% improvement per month
      returnRate = Math.min(100, initialData.retentionRate + (index * improvement));
    }
    
    // Calculate ROI - showing the value generated by volunteer hours
    // ROI is calculated as: (Total Value of Volunteer Hours / Company Investment) * 100
    // Where value = hours * $25 (estimated value per hour)
    const roi = initialData.companyInvestment > 0 
      ? (newHours * 25 / initialData.companyInvestment) * 100 
      : 0;
    
    simulationData.push({
      month,
      totalVolunteers: newVolunteers,
      totalHours: newHours,
      studentsReached: newStudentsReached,
      returnRate: parseFloat(returnRate.toFixed(2)),
      roi: parseFloat(roi.toFixed(2))
    });
    
    // Update for next iteration
    currentVolunteers = newVolunteers;
    currentHours = newHours;
    currentStudentsReached = newStudentsReached;
  });
  
  return simulationData;
}

export function generateTimeBasedChartData(simulationData: TimeBasedMetrics[]) {
  return simulationData.map(item => ({
    name: item.month,
    volunteers: item.totalVolunteers,
    hours: item.totalHours,
    students: item.studentsReached,
    roi: item.roi
  }));
}